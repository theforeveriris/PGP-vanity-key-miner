// 数值证明: NIST P-256 单轮特形约减 (标准算法)
//
// 输入: c = a*b < 2^512, 拆: c = s0 + s1*2^128 + s2*2^256 + s3*2^384
//   s0 = c mod 2^128, s1 = (c>>128) mod 2^128, s2 = (c>>256) mod 2^128, s3 = c>>384
// 2^256 = 2^224 - 2^192 - 2^96 + 1 (mod p)
// 2^384 = 2^112 + 2^32 - 2^-64 - 2^-192? 不用负指数: 2^384 = 2^128 * 2^256
//        = 2^128*(2^224 - 2^192 - 2^96 + 1) = 2^352 - 2^320 - 2^224 + 2^128
//   2^256+128 = 2^128 * 2^256 = 2^352 - 2^320 - 2^224 + 2^128
// T = s0 + s1*2^128 + s2*(2^224 - 2^192 - 2^96 + 1) + s3*(2^352 - 2^320 - 2^224 + 2^128)
//   = s0 + s1*2^128 + s2*2^224 - s2*2^192 - s2*2^96 + s2 + s3*2^352 - s3*2^320 - s3*2^224 + s3*2^128
// 注意 s3*2^352 仍然 > 2^256 (352 > 256)! 需要 A = s3*2^352 拆: 
//   实际标准算法 (NIST SP 800-186 /openssl): 用 4 个 64 位字或按他们的分组。
// 经典实现 (针对 32 位 limb 8 个):
//   c = a*b 是 16 limb。拆成: A = limb[0..3]*2^0? 不对 — 按官方的分组是 128 位 4 组。
// 但 s2*s2^224 项可以 > 2^256: s2 < 2^128, s2*2^224 < 2^352。 
// T 的所有项加起来最大: s2*2^352 < 2^480。 仍然有高位!
// 标准解决: 第二轮: 把 > 2^256 的部分再折一次 (值已经 < 2^480, 折后 < 2^225) — 2 轮收敛!
// 我上轮的 8-12 轮问题在于把 2^256 段整体滚动; 128 位分组一轮砍 128 位: 512->384->256 -> <2 轮!
// 用 128 位分组 (每 4 limb 一组) 实现 2 轮版:
//   round 1: 512 -> ~448? 具体: 2^384*s3 折成 <2^352 项, 2^256*s2 折成 <2^225。
//   结果 T < 2^256 + s3*2^352? 不 — s3*2^352 项还在!
// 哦 s3*2^352 = s3*2^128 * 2^224 - ... 同样展开 (2^352 = 2^128*2^256 mod p
//   = 2^128*2^224 - 2^128*2^192 - 2^128*2^96 + 2^128 = 2^352 - 2^320 - 2^224 + 2^128)
// s3 < 2^128, 所以 s3*2^352 < 2^480, 用恒等式 2^352 = 2^352-p 的? 不行, 352 > 256。
// 正确做法: 2^352 mod p = 2^352 - 3p (因为 2^352 < 3p < 2^353)。 具体值算一次常数。
// 标准 NIST 算法直接用公式: 参考 FIPS 186-4 D.2.3 / SP 800-186:
//   c = [A1..A0][B1..B0]... 官方拆法 (64位 words, 8 个):
//   r2 = t0 + t1 + t2 + t3 - (t4 + t5 + t6 + t7)*alpha... 
// 我直接用 128 位组的两轮版, 每轮把 2^256 和 2^384 段同时折掉:
//   s3*2^384: 2^384 mod p = 2^128 * 2^256 = 2^352 - 2^320 - 2^224 + 2^128 (还是 > 2^256!)
//   再拆 2^352: = 2^352 - 2*p? 计算 2^352 mod p 精确值: 2^352 - 3p (验证)。
// 所以 s3 项: s3*2^384 = s3*(2^352 - 2^320 - 2^224 + 2^128) 
//            = s3*(2^352) - s3*2^320 - s3*2^224 + s3*2^128
//   其中 s3*2^352 = s3*(2^352 - 3p) + 3p*s3 — 还是绕不开。
// 干脆用负指数恒等式 (NIST 标准): p = 2^256-2^224+2^192+2^96-1
//   2^256 = 2^224 - 2^192 - 2^96 + 1
//   2^224 = -2^192 + 2^256... 换个思路: 除以 2^64: 2^192 ≡ 2^160 - 2^128 - 2^32 + 2^-64?
// 不引入负指数。 简洁方案: **两轮 2^256 段折叠, 但第二轮的 hi 已经 < 2^225**:
//   round 1: hi < 2^256 (512 位折 256 位)
//   round 2: hi < 2^225 (因为 total - hi*p < 2^225)
//   round 3: hi < 2^193
//   ...每轮减 32 位, 8 轮。 这是我们的 v3 慢的原因。
// 快路径: **第二轮开始 hi < 2^225 < 2^256**, 此时 hi*(2^224-2^192-2^96+1) < 2^225 * 2^225 < 2^450 — 还是 > 2^256。
// 换用 64 位折叠 (alpha = 2^64): 一轮砍 64 位: 512->448? no.
// 正确且被验证的快速做法是 openssl/Golang 的: 把 c 拆成 4 个 128 位块 s0..s3, 
// 然后 r = s0 + s1*beta + s2*gamma + s3*delta, 其中 beta = 2^128 mod p (常数),
// gamma = 2^256 mod p = 2^224-2^192-2^96+1 (常数), delta = 2^384 mod p (常数)。
// 这些常数本身是 < 2^225 的固定值! 每个乘法 s_i * const_k 是 128 位 x 225 位 = 不会
// 超过 2^353, 一次 3 段折叠 (总共 ~60 limb 加减) 即可归位。 这是 2 层结构。
// 让我 JS 证明这个 2 层版本。
